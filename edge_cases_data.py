_PLAYBOOK_TAG_SETS: tuple[tuple[dict[str, Any], frozenset[str]], ...] = tuple(
    (domain, frozenset(domain.get("tags", []))) for domain in EDGE_CASE_PLAYBOOK
)


def get_edge_case_checklist_for_tags(tags: list[str]) -> list[dict[str, Any]]:
    """Return the most relevant compiled edge-case playbook checks for a problem's tags."""
    tag_set = set(tags or [])
    matched: list[dict[str, Any]] = []
    seen_traps: set[str] = set()

    scored_domains: list[tuple[int, dict[str, Any]]] = []
    for domain, domain_tags in _PLAYBOOK_TAG_SETS:
        overlap = len(tag_set & domain_tags)
        if overlap > 0:
            scored_domains.append((overlap, domain))
    scored_domains.sort(key=lambda pair: -pair[0])

    if not scored_domains:
        scored_domains = [(1, EDGE_CASE_PLAYBOOK[0])]

    for _, domain in scored_domains[:2]:
        for chk in domain.get("checks", []):
            trap = chk["trap"]
            if trap not in seen_traps:
                seen_traps.add(trap)
                matched.append({
                    "domainId": domain["id"],
                    "domainTitle": domain["shortTitle"],
                    **chk,
                })
                if len(matched) >= 6:
                    return matched
    return matched
